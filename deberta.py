import jsonlines
import torch
from transformers import AutoTokenizer, AutoModelForSequenceClassification

# -----------------------------
# Config
# -----------------------------
MODEL_DIR = "./deberta_v3_clean_best_train_loss/best_train_loss"  # fine-tuned weights
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

# Paths
BASE = "/content/drive/MyDrive/Colab Notebooks/task12_clean"
DOCS_DEV_PATH = f"{BASE}/docs_dev_clean.json"
QUESTIONS_DEV_PATH = f"{BASE}/questions_dev_clean.jsonl"

# -----------------------------
# Load tokenizer + model
# -----------------------------
# Use the original pretrained tokenizer
tokenizer = AutoTokenizer.from_pretrained("microsoft/deberta-v3-base")

model = AutoModelForSequenceClassification.from_pretrained(
    MODEL_DIR,
    num_labels=4,
    problem_type="multi_label_classification"
)
model.to(DEVICE)
model.eval()

# -----------------------------
# Load dev docs
# -----------------------------
with open(DOCS_DEV_PATH, "r") as f:
    docs_data = json.load(f)

context_lookup = {}
for item in docs_data:
    tid = item["topic_id"]
    topic = item["topic"]
    for d in item["docs"]:
        uid = d["uuid"]
        parts = [d.get("title", ""), d.get("snippet", ""), d.get("content", "")]
        context_lookup[(tid, uid)] = topic + "\n" + "\n".join(parts)

# -----------------------------
# Load dev questions
# -----------------------------
dev_samples = []
with jsonlines.open(QUESTIONS_DEV_PATH) as reader:
    for q in reader:
        tid, uid = q["topic_id"], q["uuid"]
        question = q["target_event"]
        options = {"A": q["option_A"], "B": q["option_B"], "C": q["option_C"], "D": q["option_D"]}
        context = context_lookup.get((tid, uid), "")

        text = (
            f"Question: {question}\nContext: {context}\n"
            f"Options:\nA: {options['A']}\nB: {options['B']}\nC: {options['C']}\nD: {options['D']}"
        )

        gold_letters = [x.strip() for x in q["golden_answer"].split(",")]
        label = [1 if x in gold_letters else 0 for x in ["A","B","C","D"]]

        dev_samples.append((text, label))

# -----------------------------
# Evaluation
# -----------------------------
all_preds = []
all_labels = []

for text, label in dev_samples:
    inputs = tokenizer(
        text,
        truncation=True,
        padding="max_length",
        max_length=512,
        return_tensors="pt"
    ).to(DEVICE)

    with torch.no_grad():
        outputs = model(**inputs)
        logits = outputs.logits
        preds = (torch.sigmoid(logits) > 0.5).int().squeeze().tolist()

    # Ensure list of length 4
    if isinstance(preds, int):
        preds = [preds]
    all_preds.append(preds)
    all_labels.append(label)

# -----------------------------
# Compute accuracy with partial credit
# -----------------------------
total, correct = 0, 0
for pred, gold in zip(all_preds, all_labels):
    for p, g in zip(pred, gold):
        if g == 1 and p == 1:
            correct += 1
        elif g == 0 and p == 0:
            correct += 1
        # if partially correct, nothing is added (0.5 style scoring can be applied if desired)
        total += 1

accuracy = correct / total
print(f"Dev set accuracy (multi-label): {accuracy:.4f}")

