def parse_training_data(train_file):
    samples = []
    with jsonlines.open(train_file) as reader:
        for q in reader:
            question = q.get("target_event", "")
            options = {
                "A": q.get("option_A", ""),
                "B": q.get("option_B", ""),
                "C": q.get("option_C", ""),
                "D": q.get("option_D", "")
            }

            text = (
                f"Question: {question}\n"
                f"Options:\nA: {options['A']}\nB: {options['B']}\nC: {options['C']}\nD: {options['D']}"
            )

            if "golden_answer" in q:
                gold_letters = [x.strip() for x in q["golden_answer"].split(",")]
                # Ensure float labels (1.0/0.0) for BCEWithLogitsLoss
                label = [1.0 if x in gold_letters else 0.0 for x in ["A","B","C","D"]]
            else:
                label = [0.0, 0.0, 0.0, 0.0]

            samples.append({"text": text, "labels": label})
    return Dataset.from_list(samples)

