# --- Inference Settings (Optimized for clean JSON generation, non-thinking mode) ---
MAX_NEW_TOKENS = 4096
NUM_BEAMS = 1         # Greedy decoding for deterministic, structured output
TEMPERATURE = 0.001   # Near-zero temperature for reliability

# --- Helper Functions (No changes needed here, keeping the clean JSON parsing) ---

def load_data(file_path):
    """Loads data from a .jsonl file."""
    data = []
    with open(file_path, 'r', encoding='utf-8') as f:
        for line in f:
            data.append(json.loads(line))
    return data

def load_full_json(file_path):
    """Loads data from a single standard .json file."""
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def get_docs_by_topic_id(topic_id, all_docs):
    """Finds the corresponding documents for a given topic_id."""
    for doc_item in all_docs:
        if doc_item.get("topic_id") == topic_id:
            return [{k: v for k, v in doc.items() if k != 'imageUrl'} for doc in doc_item.get("docs", [])]
    return []

def get_system_prompt():
    """Defines the system prompt for structured output."""
    return """
You are an expert Logician specializing in Comprehensive Causal Analysis.
Your task is to evaluate four candidate statements (A, B, C, D) to determine if they are valid explanations for a Target Event based **strictly** on the provided context documents.

--- CRITICAL OUTPUT INSTRUCTION ---
You MUST perform all reasoning internally but output **ONLY** a single JSON object.
The JSON must have keys "A", "B", "C", and "D". Each key's value must be an object with two fields:
1. "is_correct": boolean (True if the option is a cause/part of the event, False otherwise).
2. "reasoning": string (Your brief, direct causal analysis for that specific option).

Do NOT include any extra text, commentary, markdown fences (like ```json`), or the <think> tags in your final output.
"""

def construct_prompt(question_item, context_docs):
    """Builds the user prompt."""
    event = question_item["target_event"]
    option_a = question_item["option_A"]
    option_b = question_item["option_B"]
    option_c = question_item["option_C"]
    option_d = question_item["option_D"]

    formatted_docs = "\n".join([
        f"--- Document ID: {i+1} ---\n{json.dumps(doc, ensure_ascii=False, indent=2)}"
        for i, doc in enumerate(context_docs)
    ])

    user_prompt = f"""
Analyze the relationship between the Candidate Options and the Target Event.

Target Event (The Effect to be Explained):
{event}

Available Context Documents (Evidence):
{formatted_docs}

Candidate Options:
A: {option_a}
B: {option_b}
C: {option_c}
D: {option_d}

Return the JSON evaluation where "is_correct" is True only if the option is a CAUSE or a CONSTITUENT PART of the Target Event.
"""
    return user_prompt

def parse_and_validate_json(response_text):
    """Robustly parses the JSON output from the model."""
    try:
        # Aggressively clean up residual markdown or text
        cleaned_text = re.sub(r"```json|```|<think>.*?</think>", "", response_text, flags=re.DOTALL | re.IGNORECASE).strip()

        # Locate the outermost JSON block
        start_index = cleaned_text.find('{')
        end_index = cleaned_text.rfind('}') + 1

        if start_index == -1 or end_index == -1:
            logging.warning("JSON Parsing Failed: Could not locate JSON boundaries.")
            return None

        json_str = cleaned_text[start_index:end_index]
        json_data = json.loads(json_str)

        # Structural validation
        if all(key in json_data and 'is_correct' in json_data[key] and 'reasoning' in json_data[key] for key in ["A", "B", "C", "D"]):
            return json_data

        logging.warning("JSON Validation Failed: Missing required keys (A, B, C, D, is_correct, or reasoning).")
        return None

    except json.JSONDecodeError as e:
        logging.warning(f"JSON Decoding Error: {e} | Text excerpt: {response_text[:100]}...")
        return None
    except Exception as e:
        logging.warning(f"General Parsing Error: {e}")
        return None


# --- Main Evaluation Logic ---

def main():

    # CRITICAL CHECK: Ensure the model/tokenizer are available
    if 'model' not in globals() or 'tokenizer' not in globals():
        logging.error("Model or tokenizer not found. Did you run the setup cell?")
        return

    # --- Logging Setup ---
    log_filename = f"qwen_hf_generation_{datetime.now().strftime('%Y%m%d_%H%M%S')}.log"
    logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s',
                        handlers=[logging.FileHandler(log_filename, mode='a', encoding='utf-8'), logging.StreamHandler()])
    logging.info(f"Starting Qwen (HF) structured reasoning generation...\nModel: {MODEL_NAME}\nOutput File: {OUTPUT_FILE_NAME}")

    try:
        # --- File Load Attempt with Corrected Paths ---
        questions, all_docs = load_data(EVAL_QUESTION_FILE), load_full_json(EVAL_DOCS_FILE)
    except FileNotFoundError as e:
        logging.error(f"CRITICAL ERROR: Evaluation data files not found - {e}")
        logging.error(f"Please verify paths: {EVAL_QUESTION_FILE} and {EVAL_DOCS_FILE}")
        return

    # Check if the output file exists to append data
    mode = 'a' if os.path.exists(OUTPUT_FILE_NAME) else 'w'

    with open(OUTPUT_FILE_NAME, mode, encoding='utf-8') as outfile:

        for i, question in enumerate(questions):

            topic_id = question["topic_id"]
            logging.info(f"--- Generating Structured Output for Question {i} (Topic ID: {topic_id}) ---")

            context_docs = get_docs_by_topic_id(topic_id, all_docs)
            if not context_docs:
                logging.warning(f"No documents found for Topic ID {topic_id}, skipping question.")
                continue

            user_prompt = construct_prompt(question, context_docs)

            # --- Hugging Face Chat Template ---
            messages = [
                {'role': 'system', 'content': get_system_prompt()},
                {'role': 'user', 'content': user_prompt}
            ]

            # Apply Qwen's specific chat template and encode the input
            # Setting enable_thinking=False ensures no verbose <think> tags are generated
            input_text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True, enable_thinking=False)
            inputs = tokenizer(input_text, return_tensors="pt").to(model.device)

            structured_prediction = None

            for attempt in range(2):
                try:
                    logging.info(f"Starting HF generation (Attempt {attempt + 1}/2)...")

                    with torch.no_grad():
                        outputs = model.generate(
                            **inputs,
                            max_new_tokens=MAX_NEW_TOKENS,
                            num_beams=NUM_BEAMS,
                            temperature=TEMPERATURE,
                            do_sample=False,
                            return_dict_in_generate=True,
                            output_scores=False
                        )

                    # Decode the response text
                    # Slice off the input prompt token IDs to only get the new output
                    response_ids = outputs.sequences[0][inputs.input_ids.shape[1]:]
                    model_output = tokenizer.decode(response_ids, skip_special_tokens=True).strip()

                    # Validate and parse the structured output
                    structured_prediction = parse_and_validate_json(model_output)

                    if structured_prediction:
                        logging.info(f"Successfully generated and parsed JSON on attempt {attempt + 1}.")
                        break

                    # If parsing failed, retry with a stronger prompt instruction (by appending to the user prompt)
                    logging.warning("Failed to parse JSON. Retrying with explicit instruction in prompt.")
                    # Rebuild the prompt with a strong final instruction to correct the format
                    user_prompt_retry = user_prompt + "\n\nCRITICAL: Your output must be a single, valid JSON object ONLY, starting with '{' and ending with '}'. Do not include any other text."
                    messages[-1]['content'] = user_prompt_retry # Modify the last user message for retry
                    input_text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True, enable_thinking=False)
                    inputs = tokenizer(input_text, return_tensors="pt").to(model.device)


                except Exception as e:
                    logging.error(f"Error during HF generation on attempt {attempt + 1}/2: {e}")

                if attempt == 1 and not structured_prediction:
                    logging.error(f"Both attempts failed for question (Index: {i}). Skipping.")

            # --- Output to JSONL file ---
            output_item = {
                "question_id": question.get("id", f"q_{i}"),
                "topic_id": topic_id,
                "question_data": question,
                "qwen_analysis": structured_prediction
            }

            # Write the combined item to the JSONL file
            outfile.write(json.dumps(output_item, ensure_ascii=False) + '\n')

            logging.info(f"Question {i} processed and saved to {OUTPUT_FILE_NAME}.")

    logging.info("--- Structured Analysis Generation Complete ---")

if __name__ == "__main__":
    main()

