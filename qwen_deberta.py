import re
import torch
import numpy as np
from datasets import Dataset
from transformers import AutoTokenizer, AutoModelForSequenceClassification, TrainingArguments, Trainer

# --- 1. SETUP ---
LOG_PATH = "/content/drive/MyDrive/Colab Notebooks/task12_clean/ToT_output_trainset.log"
MODEL_NAME = "microsoft/deberta-v3-base"
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

# --- 2. AGGRESSIVE LOG PARSER ---
def aggressive_log_generator():
    # Capture everything between "reasoning": " and the closing "
    # The [^"]* is changed to .*? with re.DOTALL to handle multiline reasoning
    reason_re = re.compile(r'"reasoning"\s*:\s*"(.*?)"', re.DOTALL)
    meta_re = re.compile(r"Prediction:.*?([A-D]).*?Golden:.*?([A-D])", re.IGNORECASE)

    current_block = ""
    count = 0

    with open(LOG_PATH, 'r', encoding='utf-8', errors='ignore') as f:
        for line in f:
            if "--- Evaluating Question" in line:
                if current_block:
                    # Find ALL reasoning instances in the block
                    reasons = reason_re.findall(current_block)
                    meta = meta_re.search(current_block)

                    if reasons and meta:
                        # Grab the absolute last reasoning found in the text
                        last_reason = reasons[-1].replace('\\n', ' ').strip()
                        pred = meta.group(1).upper()
                        gold = meta.group(2).upper()

                        yield {
                            "text": f"Logic: {last_reason} [SEP] Gold: {gold}",
                            "label": 0 if pred == gold else 1
                        }
                        count += 1
                current_block = ""
            current_block += line

    # Catch the last one
    if current_block:
        reasons = reason_re.findall(current_block)
        meta = meta_re.search(current_block)
        if reasons and meta:
            yield {"text": f"Logic: {reasons[-1]} [SEP] Gold: {meta.group(2)}", "label": 0 if meta.group(1)==meta.group(2) else 1}
            count += 1

    print(f"\n✅ Aggressive Search Found: {count} samples")

# --- 3. DATA PREP ---
tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
dataset = Dataset.from_generator(aggressive_log_generator)
ds = dataset.train_test_split(test_size=0.1)

def tokenize_fn(batch):
    return tokenizer(batch["text"], truncation=True, padding="max_length", max_length=512)

tokenized_ds = ds.map(tokenize_fn, batched=True)

# --- 4. TRAINING (FIXED ARGUMENTS) ---
model = AutoModelForSequenceClassification.from_pretrained(MODEL_NAME, num_labels=2).to(DEVICE)

# Renamed 'evaluation_strategy' to 'eval_strategy'
args = TrainingArguments(
    output_dir="./deberta_judge_v3",
    num_train_epochs=5,
    per_device_train_batch_size=8,
    learning_rate=2e-5,
    eval_strategy="epoch",  # FIXED KEYWORD
    logging_steps=10,
    save_strategy="epoch",
    report_to="none"
)

def compute_metrics(eval_pred):
    logits, labels = eval_pred
    preds = np.argmax(logits, axis=-1)
    return {"accuracy": (preds == labels).mean()}

trainer = Trainer(
    model=model,
    args=args,
    train_dataset=tokenized_ds["train"],
    eval_dataset=tokenized_ds["test"],
    tokenizer=tokenizer,
    compute_metrics=compute_metrics
)

print("Starting training on all available reasoning traces...")
trainer.train()

# Save the model and tokenizer properly
trainer.save_model("./deberta_judge_v3")
tokenizer.save_pretrained("./deberta_judge_v3")

