"""
DeBERTa-v3 Generator-Verifier Training Script
=============================================

This script trains a DeBERTa-v3-base model to verify the reasoning chains generated by Qwen.
It uses a Multi-Label to Binary Classification approach with a custom Focal Loss
to handle class imbalance and maximize the official 'Exact Match' score.

Key Features:
- Model: microsoft/deberta-v3-base
- Hardware Optimization: BF16 + TF32 (Optimized for A100)
- Loss Function: Focal Loss (alpha=0.5, gamma=4.0 which is aggressive, alpha = 0.25, gamma = 2.0 for stable if you want) to focus on hard negatives. 
- Metric: Custom 'Official Score' (Instance-level Exact/Partial Match).

Usage:
    python train_verifier.py
"""

import json
import os
import torch
import numpy as np
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import Dataset
from transformers import (
    AutoTokenizer, 
    AutoModelForSequenceClassification, 
    TrainingArguments, 
    Trainer
)
from sklearn.metrics import accuracy_score, precision_recall_fscore_support

# ================= Configuration =================
# Model Checkpoint
MODEL_NAME = "microsoft/deberta-v3-base"
OUTPUT_DIR = "./ckpts"
MAX_LEN = 512

# Dataset Paths (Ensure these exist in your repository)
TRAIN_DOCS = "dataset/train_data/docs.json"
TRAIN_QS = "dataset/train_data/questions.jsonl"
TRAIN_QWEN = "ToTtrain.json"

VAL_DOCS = "dataset/val_data/docs.json"
VAL_QS = "dataset/val_data/questions.jsonl"
VAL_QWEN = "ToTval.json"

# ================= Data Preprocessing Utilities =================

def load_docs_map(docs_path):
    """
    Creates a mapping from topic_id to a concatenated string of document titles.
    """
    print(f"[Data] Loading docs from {docs_path}...")
    with open(docs_path, 'r', encoding='utf-8') as f:
        docs_data = json.load(f)
    
    topic_map = {}
    for item in docs_data:
        t_id = item['topic_id']
        # Concatenate all titles under the topic using " | " separator
        titles = [d.get('title', '') for d in item.get('docs', [])]
        titles_str = " | ".join([t for t in titles if t])
        topic_map[t_id] = titles_str
    return topic_map

def load_questions_list(qs_path):
    """
    Loads questions from jsonl file into a list (indexed by line number).
    """
    print(f"[Data] Loading questions from {qs_path}...")
    qs_list = []
    with open(qs_path, 'r', encoding='utf-8') as f:
        for line in f:
            if line.strip():
                qs_list.append(json.loads(line))
    return qs_list

# ================= Dataset Definition =================

class MultiLabelVerifierDataset(Dataset):
    """
    Flattens the 4-option MCQA task into independent binary classification samples.
    Each sample represents (Question + Option + Logic) -> True/False.
    """
    def __init__(self, qwen_path, qs_path, docs_path, tokenizer, max_len=512):
        self.tokenizer = tokenizer
        self.max_len = max_len
        self.samples = []
        
        # 1. Load raw data sources
        topic_map = load_docs_map(docs_path)
        qs_list = load_questions_list(qs_path)
        
        print(f"[Data] Loading Qwen outputs from {qwen_path}...")
        with open(qwen_path, 'r', encoding='utf-8') as f:
            qwen_data = json.load(f)
            
        # 2. Flatten data: Question Level -> Option Level
        for item in qwen_data:
            q_idx = item.get("Question Index")
            if q_idx is None or q_idx >= len(qs_list):
                continue
                
            original_q = qs_list[q_idx]
            
            # Basic Info
            topic_id = original_q.get("topic_id")
            target_event = original_q.get("target_event", "")
            doc_titles = topic_map.get(topic_id, "")
            
            # Parse Golden Answer (e.g., "B,D" -> {"B", "D"})
            golden_str = original_q.get("golden_answer", "")
            golden_set = set(x.strip() for x in golden_str.replace("，", ",").split(",") if x.strip())
            
            # Generate 4 binary samples (A, B, C, D) for each question
            for opt_key in ["A", "B", "C", "D"]:
                opt_text = original_q.get(f"option_{opt_key}", "")
                
                # Retrieve reasoning generated by Qwen
                if opt_key not in item:
                    continue
                qwen_opt_content = item[opt_key]
                reasoning = qwen_opt_content.get("reasoning", "")
                
                # --- Input Construction Strategy ---
                # Order: Event + Option + Reasoning + Evidence(Titles)
                # Note: Evidence is placed at the end so it gets truncated first if max_len is exceeded.
                input_text = (
                    f"Event: {target_event} [SEP] "
                    f"Option: {opt_text} [SEP] "
                    f"Logic: {reasoning} [SEP] "
                    f"Ref_Titles: {doc_titles}"
                )
                
                # Label: 1 if option is in Golden Set, else 0
                label = 1 if opt_key in golden_set else 0
                
                self.samples.append({
                    "text": input_text,
                    "label": label
                })
                
        print(f"[Data] Constructed {len(self.samples)} binary samples from {qwen_path}.")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        item = self.samples[idx]
        encoding = self.tokenizer(
            item["text"],
            truncation=True,
            padding="max_length",
            max_length=self.max_len,
            return_tensors="pt"
        )
        return {
            "input_ids": encoding["input_ids"].squeeze(0),
            "attention_mask": encoding["attention_mask"].squeeze(0),
            "labels": torch.tensor(item["label"], dtype=torch.long)
        }

# ================= Custom Metrics (Official Score) =================

def compute_metrics(eval_pred):
    """
    Computes the Official System Score based on Instance-level exact/partial matching.
    Assumption: Validation set is ordered (4 consecutive samples = 1 Question).
    """
    logits, labels = eval_pred
    preds = np.argmax(logits, axis=-1)
    
    # 1. Standard Binary Metrics
    precision, recall, f1, _ = precision_recall_fscore_support(
        labels, preds, average='binary', zero_division=0
    )
    
    # 2. Official Score Calculation
    # Check if data length is valid (multiple of 4)
    if len(preds) % 4 != 0:
        return {'f1': f1, 'accuracy': accuracy_score(labels, preds)}
    
    num_questions = len(preds) // 4
    official_scores = []
    
    for i in range(num_questions):
        # Extract 4 predictions and 4 labels for the current question
        q_preds = preds[i*4 : (i+1)*4] 
        q_labels = labels[i*4 : (i+1)*4]
        
        # Reconstruct sets: indices 0-3 correspond to A-D
        pred_set = set([idx for idx, p in enumerate(q_preds) if p == 1])
        gold_set = set([idx for idx, l in enumerate(q_labels) if l == 1])
        
        # Scoring Logic
        if pred_set == gold_set:
            score = 1.0  # Exact Match
        elif pred_set.issubset(gold_set) and len(pred_set) > 0:
            score = 0.5  # Partial Match (Subset & Non-empty)
        else:
            score = 0.0  # Incorrect (Contains wrong option or Empty)
            
        official_scores.append(score)
        
    final_official_score = sum(official_scores) / len(official_scores) if official_scores else 0.0
    
    return {
        'official_score': final_official_score, # Primary Metric
        'f1': f1,
        'precision': precision,
        'recall': recall
    }

# ================= Custom Loss Function =================

class FocalLoss(nn.Module):
    """
    Focal Loss to address class imbalance and focus on hard examples.
    FL(p_t) = -alpha * (1 - p_t)^gamma * log(p_t)
    """
    def __init__(self, alpha=1, gamma=2, reduction='mean'):
        super(FocalLoss, self).__init__()
        self.alpha = alpha
        self.gamma = gamma
        self.reduction = reduction

    def forward(self, inputs, targets):
        ce_loss = F.cross_entropy(inputs, targets, reduction='none')
        pt = torch.exp(-ce_loss)
        focal_loss = self.alpha * (1 - pt) ** self.gamma * ce_loss

        if self.reduction == 'mean':
            return focal_loss.mean()
        elif self.reduction == 'sum':
            return focal_loss.sum()
        else:
            return focal_loss

class FocalLossTrainer(Trainer):
    """
    Custom Trainer that implements Focal Loss.
    """
    def __init__(self, alpha=1.0, gamma=2.0, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.focal_alpha = alpha
        self.focal_gamma = gamma

    def compute_loss(self, model, inputs, return_outputs=False, num_items_in_batch=None):
        labels = inputs.get("labels")
        outputs = model(**inputs)
        logits = outputs.get("logits")
        
        loss_fct = FocalLoss(alpha=self.focal_alpha, gamma=self.focal_gamma)
        loss = loss_fct(logits.view(-1, self.model.config.num_labels), labels.view(-1))
        
        return (loss, outputs) if return_outputs else loss

# ================= Main Execution =================

def main():
    # 1. Setup
    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
    
    # 2. Load Data
    print(">>> Preparing Datasets...")
    train_dataset = MultiLabelVerifierDataset(
        TRAIN_QWEN, TRAIN_QS, TRAIN_DOCS, tokenizer, max_len=MAX_LEN
    )
    val_dataset = MultiLabelVerifierDataset(
        VAL_QWEN, VAL_QS, VAL_DOCS, tokenizer, max_len=MAX_LEN
    )
    
    # 3. Load Model
    print(">>> Loading Model...")
    model = AutoModelForSequenceClassification.from_pretrained(
        MODEL_NAME, 
        num_labels=2 
    )
    
    # 4. Training Configuration (Optimized for A100)
    training_args = TrainingArguments(
        output_dir=OUTPUT_DIR,
        
        # --- Hardware Optimization (A100) ---
        bf16=True,                       # Use BF16 for stability and speed
        fp16=False,
        tf32=True,                       # TensorFloat-32
        
        # --- Batch Size Strategy ---
        # Effective Batch Size = 32 (16 per GPU * 2 accum)
        per_device_train_batch_size=16,  
        gradient_accumulation_steps=2,   
        gradient_checkpointing=False,    # Disabled for speed (A100 has enough VRAM)
        
        # --- Hyperparameters (Based on Best Run: 0.622 Official Score) ---
        num_train_epochs=15,             
        learning_rate=2e-5,              # Validated stable LR
        warmup_ratio=0.1,                
        weight_decay=0.01,               
        label_smoothing_factor=0.0,      
        
        # --- Evaluation & Logging ---
        eval_strategy="epoch",
        save_strategy="epoch",
        save_total_limit=15,             # Save all epochs for analysis
        load_best_model_at_end=True,
        metric_for_best_model="official_score", # Optimize for the competition metric directly     
        dataloader_num_workers=16,       
        report_to="none"
    )
    
    # 5. Initialize Custom Trainer
    # Parameters set to Best Practice: Alpha=0.5, Gamma=4.0
    trainer = FocalLossTrainer(
        alpha=0.5,
        gamma=4.0,
        model=model,
        args=training_args,
        train_dataset=train_dataset,
        eval_dataset=val_dataset,
        tokenizer=tokenizer,
        compute_metrics=compute_metrics,
    )
    
    # 6. Start Training
    print(">>> Starting Training...")
    trainer.train()
    
    # 7. Save Final Model
    save_path = os.path.join(OUTPUT_DIR, "final_model")
    trainer.save_model(save_path)
    tokenizer.save_pretrained(save_path)
    print(f">>> Training Complete. Model saved to {save_path}")

if __name__ == "__main__":
    main()